create function public.reserve_import_processing_artifact(
  p_artifact_key text,p_batch_id bigint,p_processing_job_id bigint,p_document_id bigint,p_unit_id text,p_stage text,
  p_manifest_schema_version text,p_artifact_schema_version text,p_artifact_version integer,p_pipeline_version text,p_attempt integer,
  p_content_sha256 text,p_content_size_bytes bigint,p_storage_bucket text,p_storage_object_path text,p_idempotency_key text,
  p_retry_of_artifact_id bigint,p_supersedes_artifact_id bigint,p_provider text,p_provider_version text,p_prompt_version text,p_model text,
  p_source_artifact_ids bigint[],p_claim_token uuid,p_expected_job_lock_version integer,p_actor_id uuid,p_correlation_id uuid
) returns jsonb language plpgsql security definer set search_path='' as $$
declare j public.pricing_import_processing_jobs%rowtype; a public.pricing_import_processing_artifacts%rowtype; source_id bigint; position integer:=0;
begin
  perform public.assert_active_pricing_admin(p_actor_id);
  select * into j from public.pricing_import_processing_jobs where id=p_processing_job_id for update;
  if not found or j.batch_id<>p_batch_id then raise exception using errcode='23503',message='artifact job and batch are invalid'; end if;
  if j.status<>'processing' or j.claim_token<>p_claim_token or j.claim_expires_at<=pg_catalog.now() then raise exception using errcode='55000',message='processing claim is invalid or expired'; end if;
  if j.lock_version<>p_expected_job_lock_version or j.correlation_id<>p_correlation_id then raise exception using errcode='40001',message='stale artifact job context'; end if;
  select * into a from public.pricing_import_processing_artifacts where idempotency_key=p_idempotency_key;
  if found then return pg_catalog.jsonb_build_object('artifactId',a.id,'artifactKey',a.artifact_key,'status',a.status,'lockVersion',a.lock_version,'idempotentReplay',true); end if;
  if p_document_id is not null and not exists(select 1 from public.pricing_import_documents where id=p_document_id and batch_id=p_batch_id) then
    raise exception using errcode='23503',message='artifact document is invalid';
  end if;
  if p_stage='document_map' and coalesce(pg_catalog.array_length(p_source_artifact_ids,1),0)<>0
    or p_stage<>'document_map' and coalesce(pg_catalog.array_length(p_source_artifact_ids,1),0)=0
  then raise exception using errcode='23514',message='artifact dependency cardinality is invalid'; end if;
  if p_retry_of_artifact_id is not null and not exists(select 1 from public.pricing_import_processing_artifacts where id=p_retry_of_artifact_id and status='failed' and batch_id=p_batch_id and processing_job_id=p_processing_job_id and stage=p_stage and attempt+1=p_attempt)
  then raise exception using errcode='23514',message='artifact retry lineage is invalid'; end if;
  if p_supersedes_artifact_id is not null and not exists(select 1 from public.pricing_import_processing_artifacts where id=p_supersedes_artifact_id and status='succeeded' and batch_id=p_batch_id and processing_job_id=p_processing_job_id and stage=p_stage)
  then raise exception using errcode='23514',message='artifact supersession lineage is invalid'; end if;
  insert into public.pricing_import_processing_artifacts(artifact_key,batch_id,processing_job_id,document_id,unit_id,stage,
    manifest_schema_version,artifact_schema_version,artifact_version,pipeline_version,attempt,correlation_id,content_sha256,
    content_size_bytes,storage_bucket,storage_object_path,idempotency_key,retry_of_artifact_id,supersedes_artifact_id,
    provider,provider_version,prompt_version,model,created_by,updated_by)
  values(p_artifact_key,p_batch_id,p_processing_job_id,p_document_id,p_unit_id,p_stage,p_manifest_schema_version,
    p_artifact_schema_version,p_artifact_version,p_pipeline_version,p_attempt,p_correlation_id,p_content_sha256,
    p_content_size_bytes,p_storage_bucket,p_storage_object_path,p_idempotency_key,p_retry_of_artifact_id,p_supersedes_artifact_id,
    p_provider,p_provider_version,p_prompt_version,p_model,p_actor_id,p_actor_id) returning * into a;
  foreach source_id in array coalesce(p_source_artifact_ids,array[]::bigint[]) loop
    insert into public.pricing_import_processing_artifact_dependencies(artifact_id,source_artifact_id,ordinal) values(a.id,source_id,position);
    position:=position+1;
  end loop;
  insert into public.pricing_audit_events(aggregate_type,aggregate_id,action,after_snapshot,reason,actor_id,correlation_id)
  values('pricing_import_processing_artifact',a.id,'insert',pg_catalog.jsonb_build_object('artifactId',a.id,'stage',a.stage,'attempt',a.attempt,'status',a.status),
    case when a.retry_of_artifact_id is not null then 'artifact retried' when a.supersedes_artifact_id is not null then 'artifact superseded' else 'artifact queued' end,p_actor_id,p_correlation_id);
  return pg_catalog.jsonb_build_object('artifactId',a.id,'artifactKey',a.artifact_key,'status',a.status,'lockVersion',a.lock_version,'idempotentReplay',false);
exception when unique_violation then
  select * into a from public.pricing_import_processing_artifacts where idempotency_key=p_idempotency_key;
  if found then return pg_catalog.jsonb_build_object('artifactId',a.id,'artifactKey',a.artifact_key,'status',a.status,'lockVersion',a.lock_version,'idempotentReplay',true); end if;
  raise;
end $$;

create function public.start_import_processing_artifact(p_artifact_id bigint,p_claim_token uuid,p_expected_lock_version integer,p_actor_id uuid,p_correlation_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare a public.pricing_import_processing_artifacts%rowtype; j public.pricing_import_processing_jobs%rowtype;
begin
  perform public.assert_active_pricing_admin(p_actor_id);
  select * into a from public.pricing_import_processing_artifacts where id=p_artifact_id for update;
  if not found then raise exception using errcode='P0002',message='processing artifact not found'; end if;
  if a.status='processing' then return pg_catalog.jsonb_build_object('artifactId',a.id,'status',a.status,'lockVersion',a.lock_version,'idempotentReplay',true); end if;
  select * into j from public.pricing_import_processing_jobs where id=a.processing_job_id;
  if j.status<>'processing' or j.claim_token<>p_claim_token or j.claim_expires_at<=pg_catalog.now() or a.correlation_id<>p_correlation_id then raise exception using errcode='55000',message='processing claim is invalid or expired'; end if;
  if a.status<>'queued' or a.lock_version<>p_expected_lock_version then raise exception using errcode='40001',message='stale artifact lock version'; end if;
  update public.pricing_import_processing_artifacts set status='processing',started_at=pg_catalog.now(),updated_by=p_actor_id where id=a.id returning * into a;
  insert into public.pricing_audit_events(aggregate_type,aggregate_id,action,after_snapshot,reason,actor_id,correlation_id)
  values('pricing_import_processing_artifact',a.id,'update',pg_catalog.jsonb_build_object('artifactId',a.id,'stage',a.stage,'attempt',a.attempt,'status',a.status),'artifact processing',p_actor_id,p_correlation_id);
  return pg_catalog.jsonb_build_object('artifactId',a.id,'status',a.status,'lockVersion',a.lock_version,'idempotentReplay',false);
end $$;

create function public.succeed_import_processing_artifact(p_artifact_id bigint,p_claim_token uuid,p_expected_lock_version integer,
  p_content_sha256 text,p_content_size_bytes bigint,p_storage_bucket text,p_storage_object_path text,p_provider_run_id text,
  p_usage_metadata jsonb,p_duration_ms integer,p_actor_id uuid,p_correlation_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare a public.pricing_import_processing_artifacts%rowtype; j public.pricing_import_processing_jobs%rowtype;
begin
  perform public.assert_active_pricing_admin(p_actor_id);
  select * into a from public.pricing_import_processing_artifacts where id=p_artifact_id for update;
  if not found then raise exception using errcode='P0002',message='processing artifact not found'; end if;
  if a.status='succeeded' and a.content_sha256=p_content_sha256::character(64) and a.content_size_bytes=p_content_size_bytes and a.storage_bucket=p_storage_bucket and a.storage_object_path=p_storage_object_path
  then return pg_catalog.jsonb_build_object('artifactId',a.id,'status',a.status,'lockVersion',a.lock_version,'idempotentReplay',true); end if;
  select * into j from public.pricing_import_processing_jobs where id=a.processing_job_id;
  if j.status<>'processing' or j.claim_token<>p_claim_token or j.claim_expires_at<=pg_catalog.now() or a.correlation_id<>p_correlation_id then raise exception using errcode='55000',message='processing claim is invalid or expired'; end if;
  if a.status<>'processing' or a.lock_version<>p_expected_lock_version then raise exception using errcode='40001',message='stale artifact lock version'; end if;
  if a.content_sha256<>p_content_sha256::character(64) or a.content_size_bytes<>p_content_size_bytes or a.storage_bucket<>p_storage_bucket or a.storage_object_path<>p_storage_object_path
  then raise exception using errcode='23514',message='verified artifact metadata does not match reservation'; end if;
  update public.pricing_import_processing_artifacts set status='succeeded',completed_at=pg_catalog.now(),provider_run_id=nullif(p_provider_run_id,''),
    usage_metadata=coalesce(p_usage_metadata,'{}'::jsonb),duration_ms=p_duration_ms,updated_by=p_actor_id where id=a.id returning * into a;
  insert into public.pricing_audit_events(aggregate_type,aggregate_id,action,after_snapshot,reason,actor_id,correlation_id)
  values('pricing_import_processing_artifact',a.id,'update',pg_catalog.jsonb_build_object('artifactId',a.id,'stage',a.stage,'attempt',a.attempt,'status',a.status,'contentSize',a.content_size_bytes,'usage',a.usage_metadata,'durationMs',a.duration_ms),'artifact succeeded',p_actor_id,p_correlation_id);
  return pg_catalog.jsonb_build_object('artifactId',a.id,'status',a.status,'lockVersion',a.lock_version,'idempotentReplay',false);
end $$;

create function public.fail_import_processing_artifact(p_artifact_id bigint,p_claim_token uuid,p_expected_lock_version integer,
  p_error_code text,p_error_message text,p_duration_ms integer,p_actor_id uuid,p_correlation_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare a public.pricing_import_processing_artifacts%rowtype; j public.pricing_import_processing_jobs%rowtype; safe_code text; safe_message text;
begin
  perform public.assert_active_pricing_admin(p_actor_id);
  safe_code:=pg_catalog.left(pg_catalog.upper(pg_catalog.regexp_replace(coalesce(p_error_code,''),'[^A-Za-z0-9_]','','g')),64);
  safe_message:=pg_catalog.left(pg_catalog.regexp_replace(coalesce(p_error_message,''),'(authorization[[:space:]]*:[[:space:]]*(bearer[[:space:]]+)?|apikey[[:space:]]*[:=][[:space:]]*|service[_-]?role[[:space:]]*[:=][[:space:]]*|bearer[[:space:]]+|sk-|sb_secret_|eyJ|postgres(?:ql)?://)[^[:space:]]+','[REDACTED]','gi'),500);
  if safe_code='' or nullif(pg_catalog.btrim(safe_message),'') is null then raise exception using errcode='22023',message='safe artifact diagnostic is required'; end if;
  select * into a from public.pricing_import_processing_artifacts where id=p_artifact_id for update;
  if not found then raise exception using errcode='P0002',message='processing artifact not found'; end if;
  if a.status='failed' then return pg_catalog.jsonb_build_object('artifactId',a.id,'status',a.status,'lockVersion',a.lock_version,'idempotentReplay',true); end if;
  select * into j from public.pricing_import_processing_jobs where id=a.processing_job_id;
  if j.status<>'processing' or j.claim_token<>p_claim_token or j.claim_expires_at<=pg_catalog.now() or a.correlation_id<>p_correlation_id then raise exception using errcode='55000',message='processing claim is invalid or expired'; end if;
  if a.status not in ('queued','processing') or a.lock_version<>p_expected_lock_version then raise exception using errcode='40001',message='stale artifact lock version'; end if;
  update public.pricing_import_processing_artifacts set status='failed',started_at=coalesce(started_at,pg_catalog.now()),completed_at=pg_catalog.now(),
    error_code=safe_code,error_message=safe_message,duration_ms=p_duration_ms,updated_by=p_actor_id where id=a.id returning * into a;
  insert into public.pricing_audit_events(aggregate_type,aggregate_id,action,after_snapshot,reason,actor_id,correlation_id)
  values('pricing_import_processing_artifact',a.id,'update',pg_catalog.jsonb_build_object('artifactId',a.id,'stage',a.stage,'attempt',a.attempt,'status',a.status,'errorCode',a.error_code,'durationMs',a.duration_ms),'artifact failed',p_actor_id,p_correlation_id);
  return pg_catalog.jsonb_build_object('artifactId',a.id,'status',a.status,'lockVersion',a.lock_version,'idempotentReplay',false);
end $$;

create function public.attach_import_processing_artifact_dependencies(p_artifact_id bigint,p_source_artifact_ids bigint[],p_actor_id uuid,p_correlation_id uuid)
returns integer language plpgsql security definer set search_path='' as $$
declare a public.pricing_import_processing_artifacts%rowtype; source_id bigint; position integer; inserted_count integer:=0;
begin
  perform public.assert_active_pricing_admin(p_actor_id);
  select * into a from public.pricing_import_processing_artifacts where id=p_artifact_id for update;
  if not found or a.correlation_id<>p_correlation_id then raise exception using errcode='P0002',message='processing artifact context not found'; end if;
  position:=coalesce((select max(ordinal)+1 from public.pricing_import_processing_artifact_dependencies where artifact_id=p_artifact_id),0);
