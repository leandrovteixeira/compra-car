create function public.protect_import_processing_artifact()
returns trigger language plpgsql security invoker set search_path='' as $$
begin
  if tg_op='DELETE' then raise exception using errcode='55000',message='processing artifacts are retained for audit'; end if;
  if old.status in ('succeeded','failed') then raise exception using errcode='55000',message='terminal processing artifact is immutable'; end if;
  if new.artifact_key is distinct from old.artifact_key or new.batch_id is distinct from old.batch_id
    or new.processing_job_id is distinct from old.processing_job_id or new.document_id is distinct from old.document_id
    or new.unit_id is distinct from old.unit_id or new.stage is distinct from old.stage
    or new.manifest_schema_version is distinct from old.manifest_schema_version
    or new.artifact_schema_version is distinct from old.artifact_schema_version
    or new.artifact_version is distinct from old.artifact_version or new.pipeline_version is distinct from old.pipeline_version
    or new.attempt is distinct from old.attempt or new.correlation_id is distinct from old.correlation_id
    or new.idempotency_key is distinct from old.idempotency_key or new.retry_of_artifact_id is distinct from old.retry_of_artifact_id
    or new.supersedes_artifact_id is distinct from old.supersedes_artifact_id
    or new.content_sha256 is distinct from old.content_sha256 or new.content_size_bytes is distinct from old.content_size_bytes
    or new.storage_bucket is distinct from old.storage_bucket or new.storage_object_path is distinct from old.storage_object_path
    or new.provider is distinct from old.provider or new.provider_version is distinct from old.provider_version
    or new.prompt_version is distinct from old.prompt_version or new.model is distinct from old.model
  then raise exception using errcode='55000',message='processing artifact identity is immutable'; end if;
  if old.status='queued' and new.status not in ('processing','failed')
    or old.status='processing' and new.status not in ('succeeded','failed')
  then raise exception using errcode='55000',message='invalid processing artifact lifecycle transition'; end if;
  return new;
end $$;

create function public.validate_import_processing_artifact_dependency()
returns trigger language plpgsql security invoker set search_path='' as $$
declare target public.pricing_import_processing_artifacts%rowtype; source public.pricing_import_processing_artifacts%rowtype; expected text;
begin
  if new.artifact_id=new.source_artifact_id then raise exception using errcode='23514',message='artifact self dependency is forbidden'; end if;
  select * into target from public.pricing_import_processing_artifacts where id=new.artifact_id;
  select * into source from public.pricing_import_processing_artifacts where id=new.source_artifact_id;
  if target.status<>'queued' then raise exception using errcode='55000',message='dependencies can only be attached while artifact is queued'; end if;
  if source.status<>'succeeded' then raise exception using errcode='55000',message='artifact dependency must be succeeded'; end if;
  if source.batch_id<>target.batch_id or source.processing_job_id<>target.processing_job_id then raise exception using errcode='23514',message='artifact dependency must belong to the same batch and job'; end if;
  if exists(
    with recursive ancestry(id) as (
      select new.source_artifact_id union
      select d.source_artifact_id from public.pricing_import_processing_artifact_dependencies d join ancestry a on d.artifact_id=a.id
    ) select 1 from ancestry where id=new.artifact_id
  ) then raise exception using errcode='23514',message='artifact dependency cycle is forbidden'; end if;
  expected:=case target.stage when 'unit_plan' then 'document_map' when 'unit_extraction' then 'unit_plan'
    when 'merge' then 'unit_extraction' when 'semantic_reconciliation' then 'merge' when 'domain_mapping' then 'semantic_reconciliation' end;
  if expected is null or source.stage<>expected then raise exception using errcode='23514',message='artifact dependency stage is incompatible'; end if;
  return new;
end $$;

