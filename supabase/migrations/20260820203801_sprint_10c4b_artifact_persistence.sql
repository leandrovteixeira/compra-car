create function public.is_valid_import_artifact_usage(p_usage jsonb)
returns boolean language sql immutable security invoker set search_path='' as $$
  select pg_catalog.jsonb_typeof(p_usage)='object'
    and not exists (
      select 1 from pg_catalog.jsonb_object_keys(p_usage) as key
      where key not in ('inputUnits','outputUnits','totalUnits')
    )
    and not exists (
      select 1 from pg_catalog.jsonb_each(p_usage) as item
      where pg_catalog.jsonb_typeof(item.value)<>'number'
        or (item.value::text)::numeric<0
        or pg_catalog.trunc((item.value::text)::numeric)<>(item.value::text)::numeric
    )
$$;

