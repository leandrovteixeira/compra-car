create table public.pricing_import_row_reviews (
  id bigint generated by default as identity,
  import_row_id bigint not null,
  decision public.pricing_review_decision not null,
  previous_status public.pricing_import_row_status not null,
  next_status public.pricing_import_row_status not null,
  notes text,
  snapshot jsonb not null,
  reviewed_at timestamp with time zone not null default now(),
  reviewed_by uuid not null,
  constraint pricing_import_row_reviews_pkey primary key (id),
  constraint pricing_import_row_reviews_import_row_id_fkey foreign key (import_row_id)
    references public.pricing_import_rows(id) on delete restrict,
  constraint pricing_import_row_reviews_reviewed_by_fkey foreign key (reviewed_by)
    references public.profiles(id) on delete restrict,
  constraint pricing_import_row_reviews_notes_check check (
    decision not in ('reject', 'request_changes')
    or nullif(btrim(notes), '') is not null
  )
);

create index pricing_import_row_reviews_import_reviewed_at_idx
  on public.pricing_import_row_reviews (import_row_id, reviewed_at desc);
create index pricing_import_row_reviews_reviewer_reviewed_at_idx
  on public.pricing_import_row_reviews (reviewed_by, reviewed_at desc);

create table public.pricing_audit_events (
  id bigint generated by default as identity,
  aggregate_type text not null,
  aggregate_id bigint not null,
  action public.pricing_audit_action not null,
  before_snapshot jsonb,
  after_snapshot jsonb,
  reason text,
  actor_id uuid,
  occurred_at timestamp with time zone not null default now(),
  correlation_id uuid not null,
  constraint pricing_audit_events_pkey primary key (id),
  constraint pricing_audit_events_actor_id_fkey foreign key (actor_id)
    references public.profiles(id) on delete set null,
  constraint pricing_audit_events_aggregate_type_check check (
    aggregate_type in (
      'product_public_price',
      'financial_parameter_set',
      'commercial_policy',
      'commercial_policy_application',
      'commercial_policy_accumulator',
      'pricing_import_batch',
      'pricing_import_row'
    )
  ),
  constraint pricing_audit_events_snapshot_check check (
    before_snapshot is not null or after_snapshot is not null
  ),
  constraint pricing_audit_events_reason_check check (
    action not in ('update', 'reject', 'archive')
    or nullif(btrim(reason), '') is not null
  )
);

create index pricing_audit_events_aggregate_occurred_at_idx
  on public.pricing_audit_events (aggregate_type, aggregate_id, occurred_at desc);
create index pricing_audit_events_actor_occurred_at_idx
  on public.pricing_audit_events (actor_id, occurred_at desc);
create index pricing_audit_events_correlation_id_idx
  on public.pricing_audit_events (correlation_id);

