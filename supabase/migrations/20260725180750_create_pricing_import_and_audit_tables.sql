create table public.pricing_import_batches (
  id bigint generated by default as identity,
  source_type public.pricing_source_type not null,
  idempotency_key text not null,
  original_file_name text,
  storage_object_path text,
  content_sha256 character(64),
  campaign_reference text,
  valid_from date,
  valid_to date,
  extractor_provider text,
  extractor_model text,
  prompt_version text,
  schema_version text not null,
  status public.pricing_import_status not null default 'uploaded',
  metadata jsonb not null default '{}'::jsonb,
  legacy_import_id bigint,
  created_at timestamp with time zone not null default now(),
  created_by uuid,
  updated_at timestamp with time zone not null default now(),
  updated_by uuid,
  reviewed_at timestamp with time zone,
  reviewed_by uuid,
  promoted_at timestamp with time zone,
  promoted_by uuid,
  lock_version integer not null default 1,
  constraint pricing_import_batches_pkey primary key (id),
  constraint pricing_import_batches_idempotency_key_key unique (idempotency_key),
  constraint pricing_import_batches_created_by_fkey foreign key (created_by)
    references public.profiles(id) on delete set null,
  constraint pricing_import_batches_updated_by_fkey foreign key (updated_by)
    references public.profiles(id) on delete set null,
  constraint pricing_import_batches_reviewed_by_fkey foreign key (reviewed_by)
    references public.profiles(id) on delete set null,
  constraint pricing_import_batches_promoted_by_fkey foreign key (promoted_by)
    references public.profiles(id) on delete set null,
  constraint pricing_import_batches_source_type_check check (source_type <> 'manual'),
  constraint pricing_import_batches_idempotency_key_check check (
    btrim(idempotency_key) <> ''
  ),
  constraint pricing_import_batches_content_sha256_check check (
    content_sha256 is null or btrim(content_sha256) ~ '^[0-9A-Fa-f]{64}$'
  ),
  constraint pricing_import_batches_dates_check check (
    valid_to is null or valid_from is null or valid_to >= valid_from
  ),
  constraint pricing_import_batches_schema_version_check check (
    btrim(schema_version) <> ''
  ),
  constraint pricing_import_batches_lock_version_check check (lock_version > 0)
);

create unique index pricing_import_batches_legacy_import_id_key
  on public.pricing_import_batches (legacy_import_id)
  where legacy_import_id is not null;
create index pricing_import_batches_status_created_at_idx
  on public.pricing_import_batches (status, created_at);
create index pricing_import_batches_content_sha256_idx
  on public.pricing_import_batches (content_sha256);
create index pricing_import_batches_source_type_created_at_idx
  on public.pricing_import_batches (source_type, created_at);

create table public.pricing_import_rows (
  id bigint generated by default as identity,
  batch_id bigint not null,
  source_row_number integer not null,
  source_page integer,
  legacy_source_table text,
  legacy_source_id bigint,
  raw_text text,
  raw_payload jsonb not null default '{}'::jsonb,
  normalized_payload jsonb not null default '{}'::jsonb,
  confidence_score numeric(5,2),
  matched_product_id integer,
  status public.pricing_import_row_status not null default 'parsed',
  issue_codes text[] not null default '{}'::text[],
  created_at timestamp with time zone not null default now(),
  created_by uuid,
  updated_at timestamp with time zone not null default now(),
  updated_by uuid,
  lock_version integer not null default 1,
  constraint pricing_import_rows_pkey primary key (id),
  constraint pricing_import_rows_batch_source_row_key unique (batch_id, source_row_number),
  constraint pricing_import_rows_batch_id_fkey foreign key (batch_id)
    references public.pricing_import_batches(id) on delete cascade,
  constraint pricing_import_rows_matched_product_id_fkey foreign key (matched_product_id)
    references public.products(id) on delete restrict,
  constraint pricing_import_rows_created_by_fkey foreign key (created_by)
    references public.profiles(id) on delete set null,
  constraint pricing_import_rows_updated_by_fkey foreign key (updated_by)
    references public.profiles(id) on delete set null,
  constraint pricing_import_rows_source_row_number_check check (source_row_number > 0),
  constraint pricing_import_rows_source_page_check check (
    source_page is null or source_page > 0
  ),
  constraint pricing_import_rows_legacy_source_table_check check (
    legacy_source_table is null
    or legacy_source_table in (
      'price_offer_import_rows',
      'price_offers_staging',
      'product_price_offers'
    )
  ),
  constraint pricing_import_rows_confidence_score_check check (
    confidence_score is null or confidence_score between 0 and 100
  ),
  constraint pricing_import_rows_lock_version_check check (lock_version > 0)
);

create unique index pricing_import_rows_legacy_source_key
  on public.pricing_import_rows (legacy_source_table, legacy_source_id)
  where legacy_source_table is not null and legacy_source_id is not null;
create index pricing_import_rows_batch_status_idx
  on public.pricing_import_rows (batch_id, status);
create index pricing_import_rows_matched_product_id_idx
  on public.pricing_import_rows (matched_product_id);

