create table public.product_public_prices (
  id bigint generated by default as identity,
  product_id integer not null,
  amount numeric(14,2) not null,
  currency_code character(3) not null default 'BRL',
  starts_on date not null,
  status public.pricing_workflow_status not null default 'draft',
  source_type public.pricing_source_type not null,
  source_import_row_id bigint,
  source_snapshot jsonb not null default '{}'::jsonb,
  reviewed_at timestamp with time zone,
  reviewed_by uuid,
  published_at timestamp with time zone,
  published_by uuid,
  created_at timestamp with time zone not null default now(),
  created_by uuid,
  updated_at timestamp with time zone not null default now(),
  updated_by uuid,
  lock_version integer not null default 1,
  constraint product_public_prices_pkey primary key (id),
  constraint product_public_prices_product_starts_on_key unique (product_id, starts_on),
  constraint product_public_prices_product_id_fkey foreign key (product_id)
    references public.products(id) on delete restrict,
  constraint product_public_prices_reviewed_by_fkey foreign key (reviewed_by)
    references public.profiles(id) on delete set null,
  constraint product_public_prices_published_by_fkey foreign key (published_by)
    references public.profiles(id) on delete set null,
  constraint product_public_prices_created_by_fkey foreign key (created_by)
    references public.profiles(id) on delete set null,
  constraint product_public_prices_updated_by_fkey foreign key (updated_by)
    references public.profiles(id) on delete set null,
  constraint product_public_prices_amount_check check (amount >= 0),
  constraint product_public_prices_currency_code_check check (currency_code = 'BRL'),
  constraint product_public_prices_zero_status_check check (
    amount <> 0 or status in ('draft', 'needs_review')
  ),
  constraint product_public_prices_published_check check (
    status <> 'published'
    or (amount > 0 and published_at is not null and published_by is not null)
  ),
  constraint product_public_prices_source_import_check check (
    source_type = 'manual' or source_import_row_id is not null
  ),
  constraint product_public_prices_lock_version_check check (lock_version > 0)
);

create index product_public_prices_product_starts_on_idx
  on public.product_public_prices (product_id, starts_on desc);
create index product_public_prices_published_product_starts_on_idx
  on public.product_public_prices (product_id, starts_on desc)
  where status = 'published';
create index product_public_prices_status_starts_on_idx
  on public.product_public_prices (status, starts_on);
create index product_public_prices_source_import_row_id_idx
  on public.product_public_prices (source_import_row_id)
  where source_import_row_id is not null;

