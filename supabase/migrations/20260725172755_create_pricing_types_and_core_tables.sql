create table public.commercial_policies (
  id bigint generated by default as identity,
  policy_type public.commercial_policy_type not null,
  scope_type public.commercial_policy_scope_type not null,
  model_brand text,
  model_name text,
  scope_snapshot jsonb not null,
  title text not null,
  description text,
  starts_on date not null,
  ends_on date,
  benefit_percentage numeric(9,6),
  down_payment_percentage numeric(9,6),
  term_months integer,
  customer_interest_rate_monthly numeric(9,6),
  calculation_method public.policy_calculation_method not null,
  financial_parameter_set_id bigint,
  status public.pricing_workflow_status not null default 'draft',
  source_type public.pricing_source_type not null,
  source_import_row_id bigint,
  supersedes_policy_id bigint,
  reviewed_at timestamp with time zone,
  reviewed_by uuid,
  published_at timestamp with time zone,
  published_by uuid,
  created_at timestamp with time zone not null default now(),
  created_by uuid,
  updated_at timestamp with time zone not null default now(),
  updated_by uuid,
  lock_version integer not null default 1,
  constraint commercial_policies_pkey primary key (id),
  constraint commercial_policies_financial_parameter_set_id_fkey
    foreign key (financial_parameter_set_id)
    references public.financial_parameter_sets(id) on delete restrict,
  constraint commercial_policies_supersedes_policy_id_fkey foreign key (supersedes_policy_id)
    references public.commercial_policies(id) on delete restrict,
  constraint commercial_policies_reviewed_by_fkey foreign key (reviewed_by)
    references public.profiles(id) on delete set null,
  constraint commercial_policies_published_by_fkey foreign key (published_by)
    references public.profiles(id) on delete set null,
  constraint commercial_policies_created_by_fkey foreign key (created_by)
    references public.profiles(id) on delete set null,
  constraint commercial_policies_updated_by_fkey foreign key (updated_by)
    references public.profiles(id) on delete set null,
  constraint commercial_policies_title_check check (btrim(title) <> ''),
  constraint commercial_policies_dates_check check (ends_on is null or ends_on >= starts_on),
  constraint commercial_policies_benefit_percentage_check check (
    benefit_percentage is null or benefit_percentage between 0 and 100
  ),
  constraint commercial_policies_down_payment_percentage_check check (
    down_payment_percentage is null or down_payment_percentage between 0 and 100
  ),
  constraint commercial_policies_customer_interest_rate_monthly_check check (
    customer_interest_rate_monthly is null
    or customer_interest_rate_monthly between 0 and 100
  ),
  constraint commercial_policies_term_months_check check (
    term_months is null or term_months > 0
  ),
  constraint commercial_policies_scope_check check (
    (
      scope_type = 'model'
      and nullif(btrim(model_brand), '') is not null
      and nullif(btrim(model_name), '') is not null
    )
    or (
      scope_type = 'product_set'
      and model_brand is null
      and model_name is null
    )
  ),
  constraint commercial_policies_supersedes_policy_check check (
    supersedes_policy_id is null or supersedes_policy_id <> id
  ),
  constraint commercial_policies_source_import_check check (
    source_type = 'manual' or source_import_row_id is not null
  ),
  constraint commercial_policies_published_check check (
    status <> 'published' or (published_at is not null and published_by is not null)
  ),
  constraint commercial_policies_lock_version_check check (lock_version > 0)
);

create index commercial_policies_status_dates_idx
