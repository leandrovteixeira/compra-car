create function public.validate_pricing_import_document_lifecycle()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if old.status = new.status then
    return new;
  end if;
  if old.status = 'uploaded' and new.status not in ('validated', 'failed', 'rejected', 'archived')
     or old.status = 'validated' and new.status not in ('ready', 'failed', 'rejected', 'archived')
     or old.status = 'ready' and new.status not in ('processing', 'failed', 'rejected', 'archived')
     or old.status = 'processing' and new.status not in ('processed', 'failed')
     or old.status = 'processed' and new.status <> 'archived'
     or old.status = 'failed' and new.status not in ('uploaded', 'rejected', 'archived')
     or old.status = 'rejected' and new.status <> 'archived'
     or old.status = 'archived' then
    raise exception using errcode = '55000', message = 'invalid pricing import document lifecycle transition';
  end if;
  return new;
end;
$$;

create function public.protect_pricing_import_document()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    raise exception using errcode = '55000', message = 'pricing import documents are retained for audit';
  end if;
  if old.status in ('processing', 'processed', 'archived') and (
    new.batch_id is distinct from old.batch_id
    or new.document_type is distinct from old.document_type
    or new.original_file_name is distinct from old.original_file_name
    or new.storage_bucket is distinct from old.storage_bucket
    or new.storage_object_path is distinct from old.storage_object_path
    or new.mime_type is distinct from old.mime_type
    or new.file_size_bytes is distinct from old.file_size_bytes
    or new.content_sha256 is distinct from old.content_sha256
    or new.source_order is distinct from old.source_order
    or new.document_role is distinct from old.document_role
  ) then
    raise exception using errcode = '55000', message = 'processed import document identity is immutable';
  end if;
  return new;
end;
$$;

