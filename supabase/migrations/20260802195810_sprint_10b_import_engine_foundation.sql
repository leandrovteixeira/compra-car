create function public.archive_import_engine_batch(
  p_batch_id bigint,
  p_expected_lock_version integer,
  p_reason text,
  p_actor_id uuid,
  p_correlation_id uuid
)
returns public.pricing_import_batches
language plpgsql
security definer
set search_path = ''
as $$
declare
  before_record public.pricing_import_batches%rowtype;
  after_record public.pricing_import_batches%rowtype;
begin
  perform public.assert_active_pricing_admin(p_actor_id);
  if p_correlation_id is null or p_expected_lock_version is null or nullif(pg_catalog.btrim(p_reason),'') is null then
    raise exception using errcode='22004', message='batch archival requires lock, reason and correlation ID';
